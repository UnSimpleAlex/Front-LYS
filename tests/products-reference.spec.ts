import { test, expect } from '@playwright/test';

test('productos: edición completa, vista previa, filtros, exportación y confirmación reversible', async ({page}) => {
  await page.goto('/iniciar-sesion');
  await page.getByRole('button',{name:'Accesos de prueba por rol'}).click();
  await page.getByRole('button',{name:'Preparar cuentas de prueba'}).click();
  await expect(page.getByText('Demo2026!',{exact:true})).toBeVisible();
  await page.getByLabel('Correo electrónico',{exact:true}).fill('administrador@demo.local');
  await page.getByLabel('Contraseña',{exact:true}).fill('Demo2026!');
  await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();
  await page.goto('/administrador/productos');
  await page.setViewportSize({width:1672,height:941});
  await expect(page.locator('.ops-sidebar')).toHaveCSS('background-color','rgb(255, 255, 255)');
  await expect(page.locator('.ops-product-list table')).toHaveCSS('display','table');
  await page.getByRole('button',{name:'Nuevo producto',exact:true}).click();
  let dialog=page.getByRole('dialog');
  await dialog.getByLabel('Nombre del producto',{exact:true}).fill('Producto referencia');
  await dialog.getByLabel('Precio (S/)',{exact:true}).fill('29.90');
  await dialog.getByLabel('Stock',{exact:true}).fill('12');
  await dialog.getByLabel('SKU',{exact:true}).fill('REF-001');
  await dialog.getByLabel('Tiempo estimado (min)',{exact:true}).fill('25');
  await dialog.getByLabel('Descripción',{exact:true}).fill('Descripción completa de prueba.');
  await dialog.getByRole('button',{name:'Agregar ingrediente'}).click();
  await dialog.getByLabel('Ingrediente 1',{exact:true}).fill('Papas crocantes');
  await dialog.getByLabel('Observaciones',{exact:true}).fill('Preparar al momento.');
  await dialog.getByRole('button',{name:'Vista previa'}).click();
  const preview=page.getByRole('dialog',{name:'Detalle del producto'});
  await expect(preview.getByRole('heading',{name:'Producto referencia'})).toBeVisible();
  await preview.getByRole('button',{name:'Cerrar',exact:true}).click();
  dialog=page.getByRole('dialog',{name:'Nuevo producto'});
  await expect(dialog.getByRole('button',{name:'Vista previa'})).toBeFocused();
  await dialog.getByRole('button',{name:'Guardar producto'}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByLabel('Buscar producto',{exact:true}).fill('REF-001');
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('button',{name:'Ver Producto referencia',exact:true}).click();
  dialog=page.getByRole('dialog');
  await dialog.getByRole('button',{name:'Ingredientes',exact:true}).click();
  await expect(dialog).toContainText('Papas crocantes');
  await expect(dialog).toContainText('25 min');
  await page.screenshot({path:'test-results/products-detail-reference.png'});
  await dialog.press('Escape');
  await page.getByRole('button',{name:'Desactivar Producto referencia',exact:true}).click();
  await expect(page.locator('tbody')).toContainText('Activo');
  await page.getByRole('dialog').getByRole('button',{name:'Cancelar',exact:true}).click();
  await expect(page.locator('tbody')).toContainText('Activo');
  await page.getByRole('button',{name:'Desactivar Producto referencia',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Desactivar producto',exact:true}).click();
  await expect(page.locator('tbody')).toContainText('Inactivo');
  await page.getByLabel('Seleccionar Producto referencia',{exact:true}).check();
  await page.getByRole('button',{name:'Activar',exact:true}).click();
  await expect(page.locator('tbody')).toContainText('Activo');
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Exportar',exact:true}).click();
  expect((await download).suggestedFilename()).toBe('productos.csv');
  await page.reload();
  await page.getByLabel('Buscar producto',{exact:true}).fill('REF-001');
  await page.getByRole('button',{name:'Editar Producto referencia',exact:true}).click();
  dialog=page.getByRole('dialog');
  await expect(dialog.getByLabel('Ingrediente 1',{exact:true})).toHaveValue('Papas crocantes');
  await expect(dialog.getByLabel('Stock',{exact:true})).toHaveValue('12');
  for(const width of [240,390,768,1024,1672,2560]) {
    await page.setViewportSize({width,height:941});
    expect(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBeTruthy();
    if([390,768,1672].includes(width)) await page.screenshot({path:`test-results/products-edit-${width}.png`});
  }
  await dialog.press('Escape');
});
